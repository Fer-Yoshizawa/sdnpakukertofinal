-- 01_schema_seed.sql — skema database absensi untuk SUPABASE (PostgreSQL)
--
-- Pengganti api/db_absensi.sql (MySQL/MariaDB) yang dipakai api/*.php.
-- Setelah migrasi ini, frontend (js/absen.js) bicara langsung ke Supabase,
-- jadi TIDAK butuh server PHP sama sekali — jalan di situs web DAN di app
-- Android (Capacitor).
--
-- CARA PAKAI:
--   1. Buka dashboard Supabase -> project kamu -> SQL Editor
--   2. Paste seluruh isi file ini -> klik Run
--   3. Lanjut ke 02_set_account_roles.sql SETELAH membuat 2 akun login
--      (langkahnya ada di supabase/SETUP.md)
--
-- SEMUA PERINTAH IDEMPOTENT (IF NOT EXISTS / ON CONFLICT DO NOTHING) —
-- aman dijalankan berulang tanpa menggandakan data.
--
-- Perbedaan penting dari skema MySQL lama:
--   * tabel `users` diganti `profiles` (id = auth.uid(), UUID) karena login
--     sekarang ditangani Supabase Auth, bukan login.php
--   * absensi.created_by kini UUID (menunjuk profiles.id), bukan INT
--   * ENUM status diganti CHECK constraint (cara Postgres)
--   * SEMUA tabel wajib RLS aktif — data hanya bisa dibaca akun yang login
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. kelas — dipakai halaman pilih kelas & rekap
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.kelas (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_kelas VARCHAR(50) NOT NULL,
  CONSTRAINT uq_kelas_nama UNIQUE (nama_kelas)
);


-- -----------------------------------------------------------------------------
-- 2. profiles — data akun di luar Supabase Auth (nama, role, kelas)
--
--    id sengaja menunjuk auth.users(id): setiap orang yang berhasil dibuat di
--    Supabase Auth otomatis dapat baris profil lewat trigger di bawah.
--
--    role : 'guru'  -> kelas dikunci ke kelasnya sendiri di UI
--           lainnya -> boleh memilih bebas lewat dropdown
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.profiles (
  id           UUID PRIMARY KEY REFERENCES auth.users (id) ON DELETE CASCADE,
  nama_lengkap VARCHAR(120) NOT NULL,
  email        VARCHAR(190) NOT NULL,
  role         VARCHAR(20)  NOT NULL DEFAULT 'guru',
  kelas_id     INTEGER NULL DEFAULT NULL REFERENCES public.kelas (id) ON DELETE SET NULL,
  CONSTRAINT uq_profiles_email UNIQUE (email)
);


-- -----------------------------------------------------------------------------
-- 3. siswa
--
--    nisn NULL-able (ada siswa belum punya NISN — UI menampilkan
--    "NISN belum terdaftar"). Unique index di Postgres menganggap NULL
--    sebagai berbeda, jadi perilakunya sama persis seperti MySQL.
--
--    UNIQUE (kelas_id, nama_lengkap) = kunci idempoten saat re-import.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.siswa (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nisn         VARCHAR(20) NULL DEFAULT NULL,
  nama_lengkap VARCHAR(120) NOT NULL,
  kelas_id     INTEGER NOT NULL REFERENCES public.kelas (id) ON DELETE CASCADE,
  CONSTRAINT uq_siswa_nisn UNIQUE (nisn),
  CONSTRAINT uq_siswa_kelas_nama UNIQUE (kelas_id, nama_lengkap)
);

CREATE INDEX IF NOT EXISTS idx_siswa_kelas ON public.siswa (kelas_id);
CREATE INDEX IF NOT EXISTS idx_siswa_nama  ON public.siswa (nama_lengkap);


-- -----------------------------------------------------------------------------
-- 4. absensi
--
--    >>> PENTING <<<
--    UNIQUE (siswa_id, tanggal) adalah SYARAT supaya upsert dari frontend
--    (ON CONFLICT (siswa_id, tanggal)) benar-benar meng-update baris lama.
--    Tanpa ini, tiap kali tombol Simpan ditekan akan terbentuk baris DUPLIKAT.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.absensi (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  siswa_id   INTEGER NOT NULL REFERENCES public.siswa (id) ON DELETE CASCADE,
  kelas_id   INTEGER NOT NULL REFERENCES public.kelas (id) ON DELETE CASCADE,
  tanggal    DATE    NOT NULL,
  status     TEXT    NOT NULL DEFAULT 'hadir'
                   CHECK (status IN ('hadir', 'izin', 'sakit', 'alpa')),
  created_by UUID    NULL DEFAULT NULL REFERENCES public.profiles (id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_absensi_siswa_tanggal UNIQUE (siswa_id, tanggal)
);

CREATE INDEX IF NOT EXISTS idx_absensi_kelas_tanggal
  ON public.absensi (kelas_id, tanggal);


-- -----------------------------------------------------------------------------
-- updated_at: otomatis ter-update saat baris diubah (pengganti
-- ON UPDATE CURRENT_TIMESTAMP milik MySQL)
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_absensi_updated_at ON public.absensi;
CREATE TRIGGER trg_absensi_updated_at
  BEFORE UPDATE ON public.absensi
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();


-- -----------------------------------------------------------------------------
-- Auto-buat profil setiap ada user baru di Supabase Auth.
-- Dipanggil otomatis saat kamu menambahkan akun lewat dashboard
-- (Authentication -> Users) MAUPUN lewat sign-up.
--
-- metadata opsional saat membuat user:
--   {"nama_lengkap": "Nama Lengkap, S.Pd.", "role": "kepsek", "kelas_id": 1}
-- Kalau kosong, nama diambil dari sebelum @ di email dan role = 'guru'.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  INSERT INTO public.profiles (id, nama_lengkap, email, role, kelas_id)
  VALUES (
    NEW.id,
    COALESCE(
      NULLIF(TRIM(NEW.raw_user_meta_data ->> 'nama_lengkap'), ''),
      SPLIT_PART(NEW.email, '@', 1)
    ),
    NEW.email,
    COALESCE(
      NULLIF(TRIM(NEW.raw_user_meta_data ->> 'role'), ''),
      'guru'
    ),
    NULLIF(NEW.raw_user_meta_data ->> 'kelas_id', '')::INTEGER
  )
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();


-- =============================================================================
-- ROW LEVEL SECURITY
--
-- Prinsipnya: akun yang BELUM login (memegang anon key saja) tidak bisa
-- menyentuh apa pun; akun yang sudah login bisa membaca data & menulis absensi.
-- Perubahan master data (tambah siswa/kelas, hapus absensi) tetap lewat
-- dashboard SQL Editor, bukan dari aplikasi.
-- =============================================================================
ALTER TABLE public.kelas    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.siswa    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.absensi  ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS kelas_select ON public.kelas;
CREATE POLICY kelas_select ON public.kelas
  FOR SELECT TO AUTHENTICATED USING (true);

DROP POLICY IF EXISTS siswa_select ON public.siswa;
CREATE POLICY siswa_select ON public.siswa
  FOR SELECT TO AUTHENTICATED USING (true);

-- Profil: hanya boleh membaca miliknya sendiri (dipakai saat login).
DROP POLICY IF EXISTS profiles_select_own ON public.profiles;
CREATE POLICY profiles_select_own ON public.profiles
  FOR SELECT TO AUTHENTICATED USING (id = auth.uid());

-- Absensi: terbaca & bisa ditulis guru/kepsek yang login.
-- (Kebijakan "guru hanya boleh kelasnya sendiri" sengaja TIDAK dipasang di
--  sini — pembatasannya sudah di UI, sama seperti perilaku PHP lama. Mau
--  dikunci juga? Lihat catatan keamanan di supabase/SETUP.md.)
DROP POLICY IF EXISTS absensi_select   ON public.absensi;
DROP POLICY IF EXISTS absensi_insert   ON public.absensi;
DROP POLICY IF EXISTS absensi_update   ON public.absensi;

CREATE POLICY absensi_select ON public.absensi
  FOR SELECT TO AUTHENTICATED USING (true);
CREATE POLICY absensi_insert ON public.absensi
  FOR INSERT TO AUTHENTICATED WITH CHECK (true);
CREATE POLICY absensi_update ON public.absensi
  FOR UPDATE TO AUTHENTICATED USING (true) WITH CHECK (true);

-- Tidak ada policy DELETE -> aplikasi tidak bisa menghapus riwayat absensi.


